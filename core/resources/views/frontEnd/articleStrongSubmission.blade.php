            <article class="article-body fs-6 lh-lg">
                <p class="lead">Judges do not award trophies to the best companies. They award trophies to the best-documented companies. Every year, strong businesses lose awards they deserved because their submission was vague, disorganised, or written at the last minute. A good entry is a skill — and like any skill, it can be learned.</p>

                <p>Here is how to prepare a submission that gives the judges no choice but to take you seriously.</p>

                <h2 class="mt-5 mb-3">1. Choose your categories strategically</h2>

                <p>More entries is not better. Entering six categories with thin submissions loses to entering two with excellent ones. Study the category definitions and pick the ones where your evidence is strongest — where you can point to specific, verifiable achievements within the eligibility period, not where you merely "do good work".</p>

                <p>Also consider the competitive landscape honestly. If a category is dominated by companies with a clear head start, a neighbouring category where your story is distinctive may be the smarter play. And never enter a category you cannot evidence: judges can tell when a submission is stretching.</p>

                <h2 class="mt-5 mb-3">2. Read the criteria like a judge will</h2>

                <p>The published criteria are the marking scheme. Print them out, and structure your submission around them — one section per criterion, in the order listed, answering each directly. Judges score against the criteria, not against your company's overall impressiveness. A brilliant story that does not map to the marking scheme scores poorly.</p>

                <p>Pay attention to weightings. If "innovation" carries 40% of the score and "client service" carries 15%, allocate your words and your best evidence accordingly.</p>

                <h2 class="mt-5 mb-3">3. Lead with evidence, not adjectives</h2>

                <p>"We are the leading provider of world-class solutions" tells a judge nothing. Numbers tell them everything. Replace every adjective with a fact:</p>

                <ul>
                    <li><strong>Instead of</strong> "rapid growth" — <strong>write</strong> "client accounts grew 68% year-on-year".</li>
                    <li><strong>Instead of</strong> "excellent customer service" — <strong>write</strong> "average first-response time of 4 minutes, with a 96% satisfaction rating across 12,000 support tickets".</li>
                    <li><strong>Instead of</strong> "innovative platform" — <strong>write</strong> "launched three proprietary features in the eligibility period, including [feature], adopted by 40% of active users within six months".</li>
                </ul>

                <p>Every claim in your submission should be followed by evidence: data, dates, documents, testimonials, or third-party verification. If a claim cannot be evidenced, cut it. One unsupported superlative makes a judge doubt the supported facts around it.</p>

                <h2 class="mt-5 mb-3">4. Tell a clear story with a beginning, middle and end</h2>

                <p>Evidence wins points, but narrative wins attention. The strongest submissions frame their facts as a story: the challenge you faced at the start of the eligibility period, what you did about it, and the measurable outcome. Judges read dozens of entries; the ones they remember are the ones with a thread running through them.</p>

                <p>A simple structure works: <strong>context</strong> (where you started), <strong>action</strong> (what you built, launched or changed), <strong>impact</strong> (what changed as a result, with numbers). Repeat that arc for each criterion, and your submission practically scores itself.</p>

                <blockquote class="border-start border-warning border-3 ps-3 my-4 fst-italic">
                    "Assume the judge knows nothing about your company and has fifteen minutes to understand why you should win. Write for that person."
                </blockquote>

                <h2 class="mt-5 mb-3">5. Use testimonials and third-party proof</h2>

                <p>Your own claims have a ceiling; other people's claims about you do not. Client testimonials, partner endorsements, press coverage, audit results and independent rankings all add weight that self-description cannot. Choose testimonials that are specific — naming the person, their role, and the outcome they experienced — over generic praise.</p>

                <p>Where the rules allow supporting documents, use them well: a one-page data summary, a product screenshot with a caption, a press clipping. Label everything clearly and reference it in the main text so the judge knows why it is there.</p>

                <h2 class="mt-5 mb-3">6. Keep it tight and readable</h2>

                <p>Respect the word limits — they exist because judges have limited time, and entries that ignore them start at a disadvantage. Within the limit, favour short paragraphs, clear headings and bullet points over dense prose. If a sentence does not add evidence or advance the story, delete it.</p>

                <p>Have someone outside your team read the draft. If they cannot explain back to you, in one sentence, why the company should win the category, the submission is not ready.</p>

                <h2 class="mt-5 mb-3">7. Start early and check the details</h2>

                <p>The most common reason good companies submit weak entries is time: the deadline arrives, and the submission is assembled in a rush. Start at least four to six weeks before the deadline. That gives you time to gather data, request testimonials, get internal sign-off, and — critically — to leave the draft alone for a few days and re-read it with fresh eyes.</p>

                <p>Finally, check the mechanics: every question answered, every required document attached, the right category selected, names and figures spelled correctly. Entries have been disqualified for less.</p>

                <h2 class="mt-5 mb-3">Mistakes that sink good entries</h2>

                <ul>
                    <li><strong>Copy-pasting marketing copy.</strong> Brochure language is written to impress customers, not to answer judging criteria. Rewrite from scratch.</li>
                    <li><strong>Ignoring the eligibility period.</strong> Achievements outside the stated window do not count, however impressive.</li>
                    <li><strong>Burying the headline.</strong> Your strongest number should appear in the first paragraph, not on page six.</li>
                    <li><strong>Entering everything.</strong> Diluted effort across many categories beats no one.</li>
                    <li><strong>Leaving evidence for "the judges to look up".</strong> They will not. Put it in the submission.</li>
                </ul>

                <p>A strong submission is not about exaggeration — it is about organisation. The companies that win consistently are rarely the ones with the most dramatic stories; they are the ones that make it easiest for judges to see, verify and score their achievements. Do the work on the page, and the trophy takes care of itself.</p>
